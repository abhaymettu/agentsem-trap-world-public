"""Optional Jev policy arm (spec 11 A3; JEV-CONSTRAINT-20260916.md is binding).

Jev decides one thing here and nothing else: how much reminder support a person gets for the
coming week. It reads a bounded, nonsecret, past only state (seven days of five standardized
deferral signals plus the reminder dose already given) and answers one Score question. The
answer is mapped to a dose on the same scale as the deterministic ``ew`` policy's
``kappa * bhat``, and that dose is the only thing that reaches the world. The latent trait,
the drift, the shadow generators, the criteria and the outcome are generated by
``trapworld.world`` exactly as in every other arm and never see a Jev output. So this is a
realistic-policy robustness arm for the D1 plus D5 correction, and the deterministic ``ew``
arm remains the central result.

Consequences of that boundary, all enforced here:

* A failed call raises ``JevArmFailed``, which makes the replicate explicitly missing. No
  output is ever filled in from another policy.
* No credential is read, printed or written anywhere except inside
  ``HttpJevTransport.__call__``, which takes it from the process environment and keeps it in
  the outgoing request object only. Tests use ``FakeJevTransport`` and never touch a network.
* The person index and the occasion index are transport-side bookkeeping so the fake and the
  recorded transports can be keyed. They are never part of the request body.

API contract read from https://docs.typesafe.ai/api.md and
https://docs.typesafe.ai/primitives/score.md on 2026-09-16.
"""

from __future__ import annotations

import json
import os
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from trapworld.params import canonical_hash, resolve
from trapworld.world import World, simulate

TYPESAFE_URL = "https://api.typesafe.ai/v1/systemone"

# The five daily deferral signals, in stream-indicator order (spec 2.4, p = 5).
CHANNELS = ("snooze", "reschedule", "late_start", "abandon", "idle")

_INSTRUCTIONS = (
    "You are helping run a habit and task app that sends people reminders about tasks they "
    "planned for themselves. For one person you are given the recent days of five daily "
    "signals. Every signal is standardized across the whole user base for that day, so 0 is "
    "the population average and a higher number means more deferral: snooze is reminders "
    "snoozed, reschedule is planned tasks moved to a later day, late_start is tasks begun "
    "after their planned time, abandon is tasks dropped before they were finished, and idle "
    "is time spent in the app without touching a task. Each day also carries reminder_dose, "
    "how much reminder support this person was already getting that day, on the same "
    "standardized scale where 0 is the average amount of support. Judge how much reminder "
    "support this person needs over the coming week."
)

_CRITERIA = (
    "On track. Planned tasks get done at or near the time they were planned, and the person "
    "is not leaning on reminders to do it. More reminders would just be noise.",
    "Mostly steady with the odd slip. A task or two slides or gets snoozed in a week and the "
    "person picks it back up without help. A reminder on the days that slip is enough.",
    "Repeatedly deferring. Tasks are pushed back, started late or dropped several times a "
    "week and the pattern is not correcting itself. The person needs a reminder on most "
    "planned tasks to stay with them.",
    "Stalled. Planned tasks are mostly being pushed back, abandoned or never started, and "
    "the reminders already being sent have not turned it around. The person needs frequent "
    "reminders through the day and a regular check-in.",
)

#: Frozen. Hashed into ``results/hashes.json`` by the runner (spec 11 A5), so nothing here
#: may drift once a grid has run: the strings are the question, and the question is the
#: policy. ``dose = kappa * (score - dose_offset) / dose_scale`` puts a four level score
#: (0 to 3) on roughly -2 kappa to 2 kappa, the scale of the ew policy's ``kappa * bhat``.
JEV_POLICY = {
    "requested_model": "jev-latest",
    "question_id": "support_need",
    "primitive": "score",
    "instructions": _INSTRUCTIONS,
    "criteria": _CRITERIA,
    "window": 7,            # days of history in the state
    "cadence": 7,           # decide at the first adaptive occasion and every 7th after
    "dose_offset": 1.5,
    "dose_scale": 0.75,
    "round_dp": 2,          # every number in the state is rounded to this many places
}

JEV_POLICY_HASH = canonical_hash(JEV_POLICY)

# The fake transport's model name. It is deliberately not a real model name so that a log
# written by the fake can never be mistaken for a Jev result.
FAKE_MODEL_NAME = "fake-jev-stub"
FAKE_CENTRE_SD = 0.3     # noise on the fake's latent level
FAKE_LEVEL_SD = 0.6      # spread of the fake's discretised normal over the levels

# Persons whose calls are written out in full for the fake arm. The fake is a plumbing
# check, so two persons are enough to show the schema; the live arm logs everyone.
FAKE_SAMPLE_PERSONS = (0, 1)

FAILURE_CLASSES = ("http_401", "http_422", "http_429", "http_529", "http_other",
                   "timeout", "connection", "schema")

_STATUS_CLASS = {401: "http_401", 422: "http_422", 429: "http_429", 529: "http_529"}
_ID_BODY_KEYS = ("request_id", "id")
_ID_HEADER_KEYS = ("x-request-id", "request-id")


# --------------------------------------------------------------------------- failures
class JevArmFailed(RuntimeError):
    """One call failed, so the whole replicate is missing. Never substituted."""

    def __init__(self, person: int, occasion: int, failure_class: str):
        super().__init__(
            f"Jev call failed for person {person} at occasion {occasion}: {failure_class}. "
            "This replicate is missing; it is never filled in from another policy."
        )
        self.person = int(person)
        self.occasion = int(occasion)
        self.failure_class = failure_class


class JevCredentialMissing(RuntimeError):
    """The live transport was called without the credential in the environment."""


class JevLogExhausted(RuntimeError):
    """A recorded replay was asked for a call that is not in the log."""


# --------------------------------------------------------------------------- the request
def build_state(view: dict, person: int, window: int) -> dict:
    """The bounded state for one person: the last ``window`` occasions and nothing else.

    Reads only ``t``, ``y``, ``dose`` and ``switch`` from the world's view, all of which
    hold occasions strictly before ``t``. Nothing person-identifying, nothing latent and
    nothing from the future goes in. Every number is rounded to ``JEV_POLICY["round_dp"]``.
    """
    t = int(view["t"])
    y = view["y"]
    dose = view["dose"]
    switch = view["switch"]
    if y.shape[2] != len(CHANNELS):
        raise ValueError(f"the Jev state names {len(CHANNELS)} channels but p = {y.shape[2]}")

    dp = JEV_POLICY["round_dp"]
    days = []
    for occ in range(max(0, t - int(window)), t):
        day = {"day": occ + 1}
        for j, name in enumerate(CHANNELS):
            day[name] = round(float(y[person, occ, j]), dp)
        day["reminder_dose"] = round(float(dose[person, occ]), dp)
        days.append(day)

    return {
        "day": t + 1,
        "days_on_adaptive_policy": int(t - int(switch[person])),
        "recent_days": days,
    }


def question_payload() -> dict:
    """The one question, exactly as it goes on the wire and into the log."""
    return {
        "type": JEV_POLICY["primitive"],
        "instructions": JEV_POLICY["instructions"],
        "criteria": list(JEV_POLICY["criteria"]),
    }


def build_request(state: dict) -> dict:
    """The POST body for https://api.typesafe.ai/v1/systemone: model, state, questions."""
    return {
        "model": JEV_POLICY["requested_model"],
        "state": state,
        "questions": {JEV_POLICY["question_id"]: question_payload()},
    }


# --------------------------------------------------------------------------- the response
def classify_status(status: int | None) -> str | None:
    """None if the call succeeded, else the failure class for an HTTP status.

    Only 200 counts as success: the documented success response is 200, so anything else,
    including another 2xx, is surfaced as a failure rather than parsed hopefully.
    """
    if status == 200:
        return None
    return _STATUS_CLASS.get(status, "http_other")


def extract_score_answer(body, question_id: str) -> dict | None:
    """The Score answer if ``body`` matches the documented schema, else None.

    Required: ``answers[question_id]`` with ``type`` "score", a numeric ``score``, a
    non-empty ``probabilities`` map, a ``legend`` map and a numeric ``confidence``
    (/primitives/score.md). Top level ``model`` and ``usage`` are optional here even though
    /api.md lists them, because the worked example response in /primitives/score.md carries
    only ``answers``; a missing ``model`` is logged as a null returned model, never guessed.
    """
    if not isinstance(body, dict):
        return None
    answers = body.get("answers")
    if not isinstance(answers, dict):
        return None
    answer = answers.get(question_id)
    if not isinstance(answer, dict) or answer.get("type") != "score":
        return None
    score, probs = answer.get("score"), answer.get("probabilities")
    legend, confidence = answer.get("legend"), answer.get("confidence")
    if isinstance(score, bool) or not isinstance(score, (int, float)):
        return None
    if not isinstance(probs, dict) or not probs:
        return None
    if not isinstance(legend, dict):
        return None
    if isinstance(confidence, bool) or not isinstance(confidence, (int, float)):
        return None
    return {"score": float(score), "probabilities": probs,
            "confidence": float(confidence), "legend": legend}


def extract_request_id(body, headers) -> str | None:
    """A request or trace id only if the service returned one. Never invented.

    The two documentation pages do not promise any such field, so this looks in the body
    (``request_id``, ``id``) and the response headers (``x-request-id``, ``request-id``)
    and returns None when none of them is there.
    """
    if isinstance(body, dict):
        for key in _ID_BODY_KEYS:
            value = body.get(key)
            if isinstance(value, str) and value:
                return value
    if headers:
        lower = {str(k).lower(): v for k, v in dict(headers).items()}
        for key in _ID_HEADER_KEYS:
            value = lower.get(key)
            if isinstance(value, str) and value:
                return value
    return None


# --------------------------------------------------------------------------- transports
@dataclass
class TransportResult:
    """What one attempted call returned. ``failure_class`` is None only on success."""

    status: int | None
    body: dict | None
    latency_ms: float
    failure_class: str | None
    request_id: str | None = None
    returned_model: str | None = None


# A transport is any callable ``transport(request, person=, occasion=) -> TransportResult``.
# ``person`` and ``occasion`` are local bookkeeping, not part of the request: the fake and
# the recorded transports key on them, and the live transport ignores them.


def _recent_channel_mean(state: dict) -> float:
    """Mean over the recent days of each day's mean deferral signal. 0 with no history."""
    days = state.get("recent_days") or []
    if not days:
        return 0.0
    return float(np.mean([[day[name] for name in CHANNELS] for day in days]))


class FakeJevTransport:
    """A schema-valid stand-in for the service. Deterministic, offline, not a Jev result.

    The answer for a call is drawn from a generator derived from ``ss`` and the call's
    (person, occasion), so it does not depend on the order the calls are made in, and a
    replicate replays identically. ``latency_ms`` is really measured, so it is the one field
    that is not reproducible; nothing downstream reads it.
    """

    def __init__(self, ss: np.random.SeedSequence, fail_rate: float = 0.0,
                 fail_at: tuple[int, int] | None = None, request_id: str | None = None):
        self.ss = ss
        self.fail_rate = float(fail_rate)
        self.fail_at = None if fail_at is None else (int(fail_at[0]), int(fail_at[1]))
        self.request_id = request_id

    def _generator(self, person: int, occasion: int) -> np.random.Generator:
        child = np.random.SeedSequence(
            entropy=self.ss.entropy,
            spawn_key=tuple(self.ss.spawn_key) + (int(person), int(occasion)),
            pool_size=self.ss.pool_size,
        )
        return np.random.Generator(np.random.PCG64(child))

    def __call__(self, request: dict, person: int = 0, occasion: int = 0) -> TransportResult:
        start = time.perf_counter()
        rng = self._generator(person, occasion)
        draw = rng.random()  # always consumed first, so fail_rate does not shift the answer

        if self.fail_at == (int(person), int(occasion)) or draw < self.fail_rate:
            return TransportResult(
                status=529, body=None, latency_ms=(time.perf_counter() - start) * 1e3,
                failure_class="http_529", request_id=self.request_id, returned_model=None,
            )

        question = request["questions"][JEV_POLICY["question_id"]]
        criteria = list(question["criteria"])
        levels = np.arange(len(criteria), dtype=float)
        centre = (float(np.clip(1.5 + 0.75 * _recent_channel_mean(request["state"]), 0.0, 3.0))
                  + FAKE_CENTRE_SD * float(rng.standard_normal()))
        weights = np.exp(-0.5 * ((levels - centre) / FAKE_LEVEL_SD) ** 2)
        probs = weights / weights.sum()

        body = {
            "model": FAKE_MODEL_NAME,
            "answers": {JEV_POLICY["question_id"]: {
                "type": "score",
                "score": float((levels * probs).sum()),
                "probabilities": {str(i): float(probs[i]) for i in range(len(criteria))},
                "legend": {str(i): criteria[i] for i in range(len(criteria))},
                "confidence": float(probs.max()),
            }},
        }  # no usage: the fake spends nothing, so it reports nothing
        return TransportResult(
            status=200, body=body, latency_ms=(time.perf_counter() - start) * 1e3,
            failure_class=None, request_id=self.request_id, returned_model=FAKE_MODEL_NAME,
        )


class HttpJevTransport:
    """The live transport. The credential is read from the environment inside the call only.

    It is never stored on the instance, never logged, never returned and never written to
    disk: it exists as a local string and inside the outgoing request's header for the
    duration of one call. Nothing in the test suite exercises this path.
    """

    def __init__(self, timeout_s: float = 30.0, env_var: str = "TYPESAFE_API_KEY"):
        self.timeout_s = float(timeout_s)
        self.env_var = env_var

    def __call__(self, request: dict, person: int = 0, occasion: int = 0) -> TransportResult:
        key = os.environ.get(self.env_var)
        if not key:
            raise JevCredentialMissing(
                f"{self.env_var} is not set in this process. The Jev credential is injected "
                "into one live run's environment from the vault and is never stored."
            )
        http_request = urllib.request.Request(
            TYPESAFE_URL,
            data=json.dumps(request).encode("utf-8"),
            headers={"Authorization": f"Bearer {key}",
                     "Content-Type": "application/json",
                     "Accept": "application/json"},
            method="POST",
        )
        del key

        start = time.perf_counter()
        try:
            with urllib.request.urlopen(http_request, timeout=self.timeout_s) as response:
                status = int(response.status)
                raw = response.read()
                headers = dict(response.headers.items())
        except urllib.error.HTTPError as exc:
            # The error body is not carried into the log: only the class and any trace id.
            return TransportResult(
                status=int(exc.code), body=None,
                latency_ms=(time.perf_counter() - start) * 1e3,
                failure_class=classify_status(int(exc.code)),
                request_id=extract_request_id(None, getattr(exc, "headers", None)),
            )
        except urllib.error.URLError as exc:
            failed = "timeout" if isinstance(exc.reason, TimeoutError) else "connection"
            return TransportResult(status=None, body=None,
                                   latency_ms=(time.perf_counter() - start) * 1e3,
                                   failure_class=failed)
        except TimeoutError:
            return TransportResult(status=None, body=None,
                                   latency_ms=(time.perf_counter() - start) * 1e3,
                                   failure_class="timeout")
        latency_ms = (time.perf_counter() - start) * 1e3

        failure_class = classify_status(status)
        try:
            body = json.loads(raw)
        except (ValueError, TypeError):
            body = None
            failure_class = failure_class or "schema"
        if failure_class is None and extract_score_answer(body, JEV_POLICY["question_id"]) is None:
            failure_class = "schema"
        returned_model = body.get("model") if isinstance(body, dict) else None
        return TransportResult(
            status=status, body=body if failure_class is None else None,
            latency_ms=latency_ms, failure_class=failure_class,
            request_id=extract_request_id(body, headers),
            returned_model=returned_model if isinstance(returned_model, str) else None,
        )


class RecordedJevTransport:
    """Replay a JSONL log written by ``JevLog``, keyed by (person, occasion).

    This is how a live run is reproduced offline: same log, same doses, no credential and no
    network. A record is consumed once, so a repeat or a call the log never saw raises.
    """

    def __init__(self, path):
        self.path = Path(path)
        self.records: dict[tuple[int, int], dict] = {}
        with open(self.path, encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                record = json.loads(line)
                self.records[(int(record["person"]), int(record["occasion"]))] = record

    def __call__(self, request: dict, person: int = 0, occasion: int = 0) -> TransportResult:
        key = (int(person), int(occasion))
        record = self.records.pop(key, None)
        if record is None:
            raise JevLogExhausted(
                f"no recorded Jev call for person {key[0]} at occasion {key[1]} in {self.path}"
            )
        answer = record.get("answer")
        body = None
        if answer is not None:
            body = {"model": record.get("returned_model"),
                    "answers": {JEV_POLICY["question_id"]: {"type": "score", **answer}}}
            if "usage" in record:
                body["usage"] = record["usage"]
        return TransportResult(
            status=record.get("http_status"), body=body,
            latency_ms=float(record.get("latency_ms") or 0.0),
            failure_class=record.get("failure_class"),
            request_id=record.get("request_id"),
            returned_model=record.get("returned_model"),
        )


# --------------------------------------------------------------------------- logging
class JevLog:
    """One JSONL record per call, with the schema the constraint note requires.

    Keys, in order: arm, cell_id, rep, person, occasion, timestamp_utc, requested_model,
    returned_model, question, state, answer, latency_ms, http_status, failure_class; then
    request_id only when the service returned one and usage only when the body carried one.
    Nothing secret can reach this file: the state is bounded and standardized, and the
    credential never leaves ``HttpJevTransport.__call__``.

    ``sample_persons`` limits which persons are written out; every call is still counted in
    ``summary()``, and a failed call is always written whatever the sampling, because a
    failure is the one record the run has to be able to show.

    A log owns its file: constructing one truncates the path, so one replicate is one file.
    """

    def __init__(self, path=None, sample_persons=None, arm: str = "jev"):
        self.path = None if path is None else Path(path)
        self.sample_persons = (None if sample_persons is None
                               else {int(p) for p in sample_persons})
        self.arm = arm
        self.records: list[dict] = []
        self.n_calls = 0
        self.n_failed = 0
        self._latency_sum = 0.0
        self._failure_classes: dict[str, int] = {}
        self._returned_models: set[str] = set()
        if self.path is not None:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.path.write_text("", encoding="utf-8")

    def _writes(self, person: int, failure_class: str | None) -> bool:
        return (failure_class is not None or self.sample_persons is None
                or int(person) in self.sample_persons)

    def record(self, *, cell_id, rep, person, occasion, state, result: TransportResult,
               answer: dict | None, failure_class: str | None) -> dict | None:
        self.n_calls += 1
        self._latency_sum += float(result.latency_ms)
        if failure_class is not None:
            self.n_failed += 1
            self._failure_classes[failure_class] = self._failure_classes.get(failure_class, 0) + 1
        if result.returned_model is not None:
            self._returned_models.add(result.returned_model)
        if not self._writes(person, failure_class):
            return None

        record = {
            "arm": self.arm,
            "cell_id": cell_id,
            "rep": rep,
            "person": int(person),
            "occasion": int(occasion),
            "timestamp_utc": datetime.now(timezone.utc).isoformat(),
            "requested_model": JEV_POLICY["requested_model"],
            "returned_model": result.returned_model,
            "question": question_payload(),
            "state": state,
            "answer": answer,
            "latency_ms": round(float(result.latency_ms), 3),
            "http_status": result.status,
            "failure_class": failure_class,
        }
        if result.request_id is not None:
            record["request_id"] = result.request_id
        usage = result.body.get("usage") if isinstance(result.body, dict) else None
        if usage is not None:
            record["usage"] = usage

        self.records.append(record)
        if self.path is not None:
            with open(self.path, "a", encoding="utf-8") as handle:
                handle.write(json.dumps(record) + "\n")
        return record

    def summary(self) -> dict:
        return {
            "n_calls": self.n_calls,
            "n_failed": self.n_failed,
            "failure_classes": dict(sorted(self._failure_classes.items())),
            "mean_latency_ms": (self._latency_sum / self.n_calls) if self.n_calls else 0.0,
            "returned_models": sorted(self._returned_models),
            "n_logged": len(self.records),
        }


# --------------------------------------------------------------------------- the policy
class JevPolicy:
    """``(t, view) -> dose[N]``: the callable ``simulate(..., external_policy=)`` wants.

    On a person's decision occasions (their first adaptive occasion and every ``cadence``
    after) one request goes out for that person, and the resulting dose is held until the
    next decision. Non-adaptive persons get 0. A failure raises ``JevArmFailed`` once the
    call has been logged, which aborts the replicate rather than papering over it.
    """

    def __init__(self, transport, log: JevLog, kappa: float, cadence: int, window: int,
                 cell_id, rep):
        self.transport = transport
        self.log = log
        self.kappa = float(kappa)
        self.cadence = int(cadence)
        self.window = int(window)
        self.cell_id = cell_id
        self.rep = rep
        self.n_calls = 0
        self.n_failed = 0
        self._held: np.ndarray | None = None

    def __call__(self, t: int, view: dict) -> np.ndarray:
        adaptive = np.asarray(view["adaptive"])
        if self._held is None:
            self._held = np.zeros(adaptive.shape[0])
        switch = np.asarray(view["switch"])
        due = adaptive & ((t - switch) % self.cadence == 0)
        for person in np.flatnonzero(due):
            self._decide(int(person), int(t), view)
        return np.where(adaptive, self._held, 0.0)

    def _decide(self, person: int, t: int, view: dict) -> None:
        state = build_state(view, person, self.window)
        result = self.transport(build_request(state), person=person, occasion=t)
        self.n_calls += 1

        answer = extract_score_answer(result.body, JEV_POLICY["question_id"])
        failure_class = result.failure_class
        if failure_class is None and answer is None:
            failure_class = "schema"
        self.log.record(cell_id=self.cell_id, rep=self.rep, person=person, occasion=t,
                        state=state, result=result, answer=answer,
                        failure_class=failure_class)
        if failure_class is not None:
            self.n_failed += 1
            raise JevArmFailed(person, t, failure_class)

        self._held[person] = (self.kappa * (answer["score"] - JEV_POLICY["dose_offset"])
                              / JEV_POLICY["dose_scale"])


# --------------------------------------------------------------------------- runner entry
def make_transport(kind: str, ss: np.random.SeedSequence, cell_id, rep, recorded_dir=None):
    """The transport for one replicate.

    The fake runs on child 9 of the replicate's SeedSequence. Children 0 to 8 are the nine
    DGP streams (spec 3), so the fake cannot move a single draw of the world.
    """
    if kind == "fake":
        child = np.random.SeedSequence(entropy=ss.entropy,
                                       spawn_key=tuple(ss.spawn_key) + (9,),
                                       pool_size=ss.pool_size)
        return FakeJevTransport(child)
    if kind == "live":
        return HttpJevTransport()
    if kind == "recorded":
        if recorded_dir is None:
            raise ValueError('kind "recorded" needs recorded_dir')
        return RecordedJevTransport(Path(recorded_dir) / f"{cell_id}_rep{rep}.jsonl")
    raise ValueError(f"unknown Jev transport kind: {kind!r}")


def run_jev_replicate(cell: dict, ss, kind: str, log_dir, cell_id, rep,
                      recorded_dir=None) -> tuple[World | None, dict]:
    """One Jev replicate. Returns ``(world, record)``, or ``(None, record)`` if a call failed.

    The cell's policy is the external one by definition of this arm; a cell that asks for a
    different policy is a mistake and raises rather than being overridden quietly.
    """
    policy_in_cell = cell.get("policy", "external")
    if policy_in_cell != "external":
        raise ValueError(f'a Jev replicate needs policy "external", not {policy_in_cell!r}')
    if not isinstance(ss, np.random.SeedSequence):
        ss = np.random.SeedSequence(ss)

    transport = make_transport(kind, ss, cell_id, rep, recorded_dir)
    path = None if log_dir is None else Path(log_dir) / f"{cell_id}_rep{rep}.jsonl"
    log = JevLog(path=path,
                 sample_persons=FAKE_SAMPLE_PERSONS if kind == "fake" else None,
                 arm=f"jev_{kind}")
    policy = JevPolicy(transport, log, kappa=float(resolve(cell)["kappa"]),
                       cadence=JEV_POLICY["cadence"], window=JEV_POLICY["window"],
                       cell_id=cell_id, rep=rep)

    failure = None
    world = None
    try:
        world = simulate({**cell, "policy": "external"}, ss, external_policy=policy)
    except JevArmFailed as exc:
        failure = {"person": exc.person, "occasion": exc.occasion,
                   "failure_class": exc.failure_class}

    record = {"arm": f"jev_{kind}",
              "status": "failed" if failure is not None else "ok",
              "failure": failure,
              **log.summary()}
    return world, record
